# Real extraction and actual Shiny turns; model requests are captured locally.
source("tests/helpers.R")
app <- load_assistant()
checks <- 0L
check <- function(ok,message) {if(!isTRUE(ok))stop(message,call.=FALSE);checks<<-checks+1L;cat("PASS",message,"\n")}
root <- tempfile("document-tests-");dir.create(root)
make <- function(name,body) {path<-file.path(root,name);writeBin(charToRaw(enc2utf8(body)),path);path}
fails <- function(expr) inherits(tryCatch(force(expr),error=identity),"error")
notes <- make("notes.txt","Монгол текст\r\nKeep x <- 0.001 & y != 10L.\r\nDo not change the task.")
doc <- app$make_document_attachment(notes,"notes.txt")
check(grepl("Монгол текст",doc$preview,fixed=TRUE) && grepl("x <- 0.001 & y != 10L",doc$preview,fixed=TRUE),"Unicode text and code operators survive local reading")
check(!grepl("\r",doc$preview,fixed=TRUE),"Windows line endings are normalized")
bom <- file.path(root,"bom.txt");writeBin(c(as.raw(c(239,187,191)),charToRaw("BOM text")),bom)
check(identical(app$document_text(bom),"BOM text"),"UTF-8 BOM is removed")
utf16 <- file.path(root,"utf16.txt");writeBin(c(as.raw(c(255,254)),as.raw(c(65,0,66,0))),utf16)
check(identical(app$document_text(utf16),"AB"),"Windows UTF-16 LE text with BOM is decoded")
utf16be <- file.path(root,"utf16be.txt");writeBin(c(as.raw(c(254,255)),as.raw(c(0,65,0,66))),utf16be)
check(identical(app$document_text(utf16be),"AB"),"UTF-16 BE text with BOM is decoded")
binary <- file.path(root,"binary.txt");writeBin(as.raw(c(65,0,66)),binary)
check(fails(app$make_document_attachment(binary,"binary.txt")),"binary data renamed as text is rejected")
bad <- file.path(root,"bad.txt");writeBin(as.raw(c(255,128,65)),bad)
check(fails(app$make_document_attachment(bad,"bad.txt")),"ambiguous invalid text encoding is reported instead of silently corrupted")
empty <- make("empty.txt"," \n\t")
check(fails(app$make_document_attachment(empty,"empty.txt")),"empty text is rejected")
check(fails(app$make_document_attachment(notes,"notes.exe")),"unsupported extensions are rejected")
source_code <- make("example.R",'stop("MUST_NOT_EXECUTE")\nx <- 1')
check(grepl("MUST_NOT_EXECUTE",app$make_document_attachment(source_code,"example.R")$preview,fixed=TRUE),"R uploads are read as text without execution")
csv <- make("data.csv",'"ID","Score value","Comment"\n"001","1.20e-03","comma, quote ""kept"""\n"002","NA","two\nlines"\n')
table <- app$make_document_attachment(csv,"data.csv")
check(grepl("2 row(s)",table$summary,fixed=TRUE) && grepl("3 column(s)",table$summary,fixed=TRUE) && grepl("Score value",table$summary,fixed=TRUE),"CSV parsing preserves original headers and handles quoted newlines")
check(grepl('"001","1.20e-03"',table$preview,fixed=TRUE),"CSV preview preserves identifiers and numeric spellings")
tsv <- make("data.tsv","id\tvalue\n01\t42\n")
check(grepl("2 column(s)",app$make_document_attachment(tsv,"data.tsv")$summary,fixed=TRUE),"TSV uses the tab separator")
invalid <- make("invalid.csv","a,b\n1,2,3\n4,5\n")
check(fails(app$make_document_attachment(invalid,"invalid.csv")),"inconsistent CSV records are rejected")
wide <- make("wide.csv",paste(rep("column",201L),collapse=","))
check(fails(app$make_document_attachment(wide,"wide.csv")),"oversized table width is bounded")
many <- make("many.csv",paste(c("id,value",paste0(1:1002,",42")),collapse="\n"))
check(grepl("preview only",app$make_document_attachment(many,"many.csv")$summary,fixed=TRUE),"large CSV row counts are not falsely described as complete")
long <- make("long.md",paste(c(rep("Unrelated paragraph.",1000L),"TARGETWORD: the answer is 73.",rep("Another paragraph.",1000L)),collapse="\n"))
large <- app$make_document_attachment(long,"long.md");large$number <- 1L
excerpt <- app$document_context(list(large),"TARGETWORD",max_chars=5000L)
check(nchar(excerpt)<=5000L && grepl("answer is 73",excerpt,fixed=TRUE) && grepl("selected excerpts",excerpt,fixed=TRUE),"large documents retrieve relevant excerpts within a fixed request budget")
line <- make("single.txt",paste0(strrep("a",10000L)," UNIQUE_TARGET_81 ",strrep("b",10000L)))
single <- app$make_document_attachment(line,"single.txt");single$number<-1L
check(grepl("UNIQUE_TARGET_81",app$document_context(list(single),"UNIQUE_TARGET_81",max_chars=3000L),fixed=TRUE),"retrieval keeps a requested match inside a very long single line")
paged <- list(number=1L,label="long.pdf",summary="PDF · 2 pages",chunks=list(
  list(label="page 1",text=strrep("irrelevant ",1000L)),list(label="page 2",text=paste0("REQUESTED_PAGE_2 ",strrep("details ",1000L)))))
check(grepl("REQUESTED_PAGE_2",app$document_context(list(paged),"2-р хуудсыг тайлбарла",max_chars=3000L),fixed=TRUE),"Mongolian page references select the requested page from a long PDF")
payload <- function(path)paste0("data:application/octet-stream;base64,",jsonlite::base64_enc(readBin(path,"raw",file.info(path)$size)))
decoded <- app$decode_document_upload(payload(notes),"notes.txt",root)
check(identical(readBin(decoded,"raw",file.info(decoded)$size),readBin(notes,"raw",file.info(notes)$size)),"file transport preserves the original bytes")
unlink(decoded)
before <- sort(list.files(root))
app$writeBin <- function(object,con,...) {base::writeBin(head(object,1L),con);stop("Synthetic disk full")}
failed_write <- fails(app$decode_document_upload(payload(notes),"notes.txt",root))
rm("writeBin",envir=app)
check(failed_write && identical(sort(list.files(root)),before),"failed document writes remove partially created temporary files")
check(fails(app$decode_document_upload("data:text/plain;base64,!!!!","notes.txt",root)),"invalid document base64 is rejected")
check(fails(app$make_document_attachment(notes,"fake.pdf")),"a renamed non-PDF is rejected by signature")
pdf <- file.path(root,"exercise.pdf")
grDevices::pdf(pdf,width=7,height=4);plot.new();text(.5,.5,"PDF page one: reference ATLAS73")
plot.new();text(.5,.5,"PDF page two: reference ORBIT42");invisible(grDevices::dev.off())
has_pdf <- requireNamespace("pdftools",quietly=TRUE)
if(!has_pdf && identical(Sys.getenv("RASSISTANT_REQUIRE_PDFTOOLS"),"true"))stop("pdftools is required for this validation")
if(has_pdf) {
  pdfdoc <- app$make_document_attachment(pdf,"exercise.pdf");pdfdoc$number<-2L
  check(grepl("2 page(s)",pdfdoc$summary,fixed=TRUE) && grepl("ATLAS73",pdfdoc$preview,fixed=TRUE),"actual PDF text is extracted with page count")
  check(grepl("[page 2]",app$document_context(list(pdfdoc),"Read page 2"),fixed=TRUE) &&
    grepl("ORBIT42",app$document_context(list(pdfdoc),"Read page 2"),fixed=TRUE),"PDF page labels and second-page contents reach context")
  blank <- file.path(root,"scan.pdf");grDevices::pdf(blank);plot.new();rect(.2,.2,.8,.8);invisible(grDevices::dev.off())
  check(fails(app$make_document_attachment(blank,"scan.pdf")),"image-only PDFs report missing text rather than claiming a successful read")
  corrupt <- make("corrupt.pdf","%PDF-1.7\nnot a valid PDF\n")
  check(fails(app$make_document_attachment(corrupt,"corrupt.pdf")),"corrupt PDF parsing is handled as an upload error")
} else cat("SKIP real PDF checks locally: pdftools missing (mandatory in Windows CI).\n")
app$initial <- app$empty_source_context();app$active_doc <- function(id=NULL)NULL
calls <- list();control<-new.env();control$fail<-FALSE
app$ask_ai <- function(system_prompt,prompt,images=character()) {
  calls[[length(calls)+1L]]<<-list(system=system_prompt,prompt=prompt,images=images)
  if(control$fail)stop("Synthetic request failure")
  "Read the uploaded source."
}
last <- function()tail(calls,1L)[[1L]]
shiny::testServer(app$server,{
  session$flushReact()
  upload <- function(path,name,id)session$setInputs(document_upload=list(data=payload(path),filename=name,nonce=id,epoch=state$upload_epoch))
  upload(notes,"notes.txt",1L)
  check(length(state$attachments)==1L && grepl("document-card",paste(as.character(output$attachment_status),collapse=""),fixed=TRUE),"document uploads have a readable preview without Source access")
  staged <- state$attachments[[1L]]$path
  upload(notes,"notes.txt",1L)
  check(length(state$attachments)==1L,"replayed document upload acknowledgements never duplicate a file")
  control$fail <- TRUE
  session$setInputs(chat_submit=list(text="Read the notes",nonce=1L))
  check(length(state$attachments)==1L && file.exists(staged) && !state$busy,"failed sends preserve document drafts and release busy state")
  control$fail <- FALSE
  session$setInputs(chat_submit=list(text="Read the notes",nonce=2L))
  check(!length(state$attachments) && !file.exists(staged) && grepl("Монгол текст",last()$prompt,fixed=TRUE),"successful document sends include extracted text and clean temporary files")
  check(!length(last()$images) && grepl("Source files were not executed",last()$prompt,fixed=TRUE),"document content is not sent as an image or treated as execution evidence")
  session$setInputs(chat_submit=list(text="Explain the code operators in that file",nonce=3L))
  check(grepl("x <- 0.001 & y != 10L",last()$prompt,fixed=TRUE),"a document follow-up reuses prior extracted content without another upload")
  upload(csv,"data.csv",2L)
  session$setInputs(chat_submit=list(text="Compare these source files",nonce=4L))
  check(grepl("Score value",last()$prompt,fixed=TRUE) && grepl("Монгол текст",last()$prompt,fixed=TRUE),"new documents can be compared with the earlier document")
  session$setInputs(chat_submit=list(text="Read notes.txt again",nonce=5L))
  check(grepl("[File 2] notes.txt",last()$prompt,fixed=TRUE),"filename references select an older successful document and ignore the failed attempt")
  session$setInputs(chat_submit=list(text="Compare files 2 and 3",nonce=51L))
  check(grepl("[File 2] notes.txt",last()$prompt,fixed=TRUE) && grepl("[File 3] data.csv",last()$prompt,fixed=TRUE),"plural numbered file references retrieve separate earlier uploads")
  session$setInputs(chat_submit=list(text="Read File 90",nonce=52L))
  check(grepl("references unavailable: File 90",last()$prompt,fixed=TRUE) && !grepl("UPLOADED DOCUMENT CONTENT",last()$prompt,fixed=TRUE),"missing file numbers are reported without substituting unrelated documents")
  session$setInputs(new_chat=1L)
  session$setInputs(chat_submit=list(text="A separate topic",nonce=6L))
  check(!grepl("UPLOADED DOCUMENT CONTENT",last()$prompt,fixed=TRUE),"New clears retained document context")
  epoch <- state$upload_epoch
  upload(notes,"notes.txt",3L);staged<-state$attachments[[1L]]$path
  session$setInputs(clear_images=1L)
  check(!length(state$attachments) && !file.exists(staged),"Remove all releases document files and previews")
  session$setInputs(document_upload=list(data=payload(notes),filename="late.txt",nonce=4L,epoch=epoch))
  check(!length(state$attachments),"late document uploads cannot reappear after reset")
  session$setInputs(cancel_image=list(nonce=5L,epoch=state$upload_epoch))
  upload(notes,"cancelled.txt",5L)
  check(!length(state$attachments),"cancelled document transfers are ignored")
  upload(source_code,"example.R",6L)
  session$setInputs(chat_submit=list(text="Run this uploaded code",nonce=7L))
  check(is.null(state$pending) && grepl("MUST_NOT_EXECUTE",last()$prompt,fixed=TRUE),"uploaded source never executes or silently runs an unrelated Source document")
  if(has_pdf) {
    upload(pdf,"exercise.pdf",7L)
    picture <- file.path(root,"picture.png");grDevices::png(picture,width=80,height=80)
    par(mar=rep(0,4));plot.new();points(.5,.5);invisible(grDevices::dev.off())
    session$setInputs(paste_image=list(image=sub("application/octet-stream","image/png",payload(picture),fixed=TRUE),filename="picture.png",nonce=8L,epoch=state$upload_epoch))
    upload(notes,"notes.txt",9L);upload(csv,"too-many.csv",10L)
    check(length(state$attachments)==3L,"mixed documents and images share the three-file limit")
    session$setInputs(chat_submit=list(text="",nonce=8L))
    check(length(last()$images)==1L && grepl("ORBIT42",last()$prompt,fixed=TRUE) && !length(state$attachments),"image and PDF uploads can be sent together without Source access")
    session$setInputs(chat_submit=list(text="Explain page 2 of exercise.pdf",nonce=9L))
    check(grepl("[page 2]",last()$prompt,fixed=TRUE) && grepl("ORBIT42",last()$prompt,fixed=TRUE),"a PDF follow-up retains its actual page text after raw upload cleanup")
    check(!length(list.files(attachment_dir)),"successful mixed uploads leave no raw or restored temporary files")
  }
})
unlink(root,recursive=TRUE)
cat(checks,"document-upload checks passed\n")
